#!/usr/bin/env python3
# PROVENANCE: FORK-ORIGINAL — fork-only file (RA timeseries project); not in upstream earthrise-media/mining-detector
"""Regenerate docs/PROVENANCE.md — per-file provenance manifest for the fork.

Classifies every git-tracked file by comparing blob hashes against
upstream/main:

  UPSTREAM-IDENTICAL  byte-identical to upstream/main (do not edit these!)
  FORK-MODIFIED       exists upstream, but content differs in this fork
  FORK-ORIGINAL       exists only in this fork

Also verifies the first-line tag convention: every FORK-* file with a
taggable extension (.py .sh .md .ipynb, plus .gitignore / requirements-lock)
outside data/ must carry a "PROVENANCE: FORK-" tag near the top; violations
are listed as warnings in the manifest.

Usage (after every upstream sync):
    git fetch upstream
    python scripts/provenance_report.py
"""
import subprocess
import datetime
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "docs" / "PROVENANCE.md"
TAGGABLE_SUFFIXES = {".py", ".sh", ".md", ".ipynb"}
TAGGABLE_NAMES = {".gitignore"}  # + requirements-lock*, handled below


def git(*args):
    return subprocess.run(["git", "-C", str(REPO), *args],
                          capture_output=True, text=True, check=True).stdout


def blobs(rev):
    """path -> blob hash for every file tracked at `rev`."""
    d = {}
    for line in git("ls-tree", "-r", rev).splitlines():
        meta, path = line.split("\t", 1)
        d[path] = meta.split()[2]
    return d


def taggable(path):
    p = Path(path)
    if path.startswith("data/"):          # data artifacts: manifest-only
        return False
    return (p.suffix in TAGGABLE_SUFFIXES or p.name in TAGGABLE_NAMES
            or p.name.startswith("requirements-lock"))


def has_tag(path):
    try:
        head = (REPO / path).read_text(errors="replace")[:2000]
    except FileNotFoundError:
        return False
    return "PROVENANCE: FORK-" in head


def main():
    head, up = blobs("HEAD"), blobs("upstream/main")
    head_rev = git("rev-parse", "--short", "HEAD").strip()
    up_rev = git("rev-parse", "--short", "upstream/main").strip()

    cats = {"FORK-ORIGINAL": [], "FORK-MODIFIED": [], "UPSTREAM-IDENTICAL": []}
    for path, h in sorted(head.items()):
        if path not in up:
            cats["FORK-ORIGINAL"].append(path)
        elif up[path] != h:
            cats["FORK-MODIFIED"].append(path)
        else:
            cats["UPSTREAM-IDENTICAL"].append(path)
    upstream_only = sorted(set(up) - set(head))

    warnings = [p for k in ("FORK-ORIGINAL", "FORK-MODIFIED") for p in cats[k]
                if taggable(p) and not has_tag(p)]

    # Archive candidates: tracked files matching known training-junk patterns
    # (new ones arrive with upstream syncs; sweep them into _archive).
    MODEL_IN_USE = "48px_v4.10b-18d-20g-21a-22bc"
    candidates = [p for p in head
                  if p.startswith(("data/sampling_locations/",
                                   "data/training_gallery/"))
                  or (p.startswith("models/") and MODEL_IN_USE not in p)]

    # Record every upstream path intentionally absent from the fork; the sync
    # script's DU rule keeps these deleted at every merge.
    arch = REPO / "_archive"
    if arch.is_dir():
        (arch / "ARCHIVED_PATHS.txt").write_text(
            "# Upstream paths intentionally absent from this fork "
            "(deletion wins at merge).\n"
            "# Generated by scripts/provenance_report.py — do not edit by hand.\n"
            + "\n".join(upstream_only) + "\n")

    lines = [
        "<!-- PROVENANCE: FORK-ORIGINAL — GENERATED FILE, do not edit by hand;"
        " regenerate with scripts/provenance_report.py -->",
        "# File provenance manifest",
        "",
        f"Generated {datetime.date.today().isoformat()} — "
        f"fork `{head_rev}` vs upstream/main `{up_rev}`.",
        "",
        f"| Category | Files |",
        f"|---|---|",
        f"| FORK-ORIGINAL | {len(cats['FORK-ORIGINAL'])} |",
        f"| FORK-MODIFIED | {len(cats['FORK-MODIFIED'])} |",
        f"| UPSTREAM-IDENTICAL | {len(cats['UPSTREAM-IDENTICAL'])} |",
        f"| upstream-only (deleted/archived here) | {len(upstream_only)} |",
        "",
    ]
    if warnings:
        lines += ["## ⚠ Missing first-line tags", ""]
        lines += [f"- `{p}`" for p in warnings] + [""]
    if candidates:
        lines += ["## ⚠ Archive candidates (training junk still tracked)", ""]
        lines += [f"- `{p}`" for p in candidates] + [""]
    for k in ("FORK-ORIGINAL", "FORK-MODIFIED", "UPSTREAM-IDENTICAL"):
        lines += [f"## {k} ({len(cats[k])})", ""]
        lines += [f"- `{p}`" for p in cats[k]] + [""]
    lines += [f"## Upstream-only — deleted/archived in this fork "
              f"({len(upstream_only)})", ""]
    lines += [f"- `{p}`" for p in upstream_only] + [""]

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(REPO)}: "
          f"{len(cats['FORK-ORIGINAL'])} original, "
          f"{len(cats['FORK-MODIFIED'])} modified, "
          f"{len(cats['UPSTREAM-IDENTICAL'])} upstream-identical, "
          f"{len(warnings)} tag warnings, "
          f"{len(candidates)} archive candidates")
    if warnings:
        print("TAG WARNINGS:", *warnings, sep="\n  ")
    if candidates:
        print("ARCHIVE CANDIDATES:", *candidates, sep="\n  ")


if __name__ == "__main__":
    main()
